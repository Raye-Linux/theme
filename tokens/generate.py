# Writes every file that comes from the Raye tokens:
#
#   colors/RayeNight.colors, colors/RayeDay.colors   KDE colour schemes
#   konsole/RayeNight.colorscheme,
#   konsole/RayeDay.colorscheme                      terminal colours
#   qml/org/raye/ui/Tokens.qml                       the QML singleton
