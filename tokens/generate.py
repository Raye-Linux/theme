def render_all(tokens):
    return {path: make(tokens) for path, make in sorted(OUTPUTS.items())}


def stale(root=ROOT, tokens=None):
    """Outputs whose file differs from what the tokens give."""
    tokens = tokens or load()
    out = []
    for path, text in render_all(tokens).items():
        full = os.path.join(root, path)
        try:
            with open(full, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            out.append(path)
    return out


def main(argv):
    tokens = load()
    bad = check_pairs(tokens)
    for mode, fg, bg, ratio, minimum in bad:
        print("contrast too low (%s): %s on %s is %.2f, needs %g"
              % (mode, fg, bg, ratio, minimum), file=sys.stderr)
    if "--check" in argv:
        old = stale(tokens=tokens)
        for path in old:
            print("out of date: %s" % path)
        return 1 if old or bad else 0
    if bad:
        return 1
    for path, text in render_all(tokens).items():
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
