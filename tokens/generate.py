def qml_accent_object(tokens, mode):
    c = {n: solid(tokens, n, mode) for n in ACCENT_TOKENS}
    return ("({ accent: %s, hover: %s, pressed: %s, text: %s, disabled: %s, onAccent: %s })"
            % tuple(qml_colour(c[n]) for n in ACCENT_TOKENS))


def selection_key(name):
    """'selection.negative' -> 'negative', the key the QML object uses."""
    return camel(name.split(".", 1)[1])


def qml_selection_object(tokens, mode):
    return "({ %s })" % ", ".join(
        "%s: %s" % (selection_key(n), qml_colour(solid(tokens, n, mode)))
        for n in SELECTION_TINTS)


def qml_selection_seeds(tokens, mode):
    """(accent-hued amounts, own-hued seeds) baked for the QML rule."""
    hue = tokens["accent_rule"]["selection"]["hue"]
    amounts = "({ %s })" % ", ".join(
        "%s: %s" % (selection_key(n), qml_num(round(tint_amount(tokens, n, mode), 6)))
        for n in SELECTION_TINTS if hue[n] == "accent")
    seeds = "({ %s })" % ", ".join(
        "%s: %s" % (selection_key(n), qml_colour(solid(tokens, n, mode)))
        for n in SELECTION_TINTS if hue[n] == "own")
    return amounts, seeds


