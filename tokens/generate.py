        prop = camel(name)
        if name == "fill.subtle.selected":
            # follows the user's accent, at the token's alpha
            out.append("    readonly property color %s: Qt.alpha(accent, night ? %s : %s)"
                       % (prop, qml_num(n["alpha"]), qml_num(d["alpha"])))
        else:
            out.append("    readonly property color %s: night ? %s : %s"
                       % (prop, q(n["color"], n["alpha"]), q(d["color"], d["alpha"])))
