# --- colour arithmetic ------------------------------------------------

def rgb(hexstr):
    """'#RRGGBB' -> (r, g, b) in 0..255."""
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})", hexstr)
    if not m:
        raise ValueError("not a #RRGGBB colour: %r" % hexstr)
    h = m.group(1)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexstr(c):
    return "#%02X%02X%02X" % tuple(int(round(v)) for v in c)


def mix(a, b, t):
    """a moved toward b by t (0..1), in sRGB, like a colour drawn at alpha t."""
    a, b = rgb(a), rgb(b)
    return hexstr(tuple(x + (y - x) * t for x, y in zip(a, b)))


def luminance(c):
    """WCAG 2 relative luminance of '#RRGGBB'."""
    def lin(v):
        v /= 255.0
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(v) for v in rgb(c))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


# --- tokens -----------------------------------------------------------

def colour(tokens, name, mode):
    """A colour token for a mode: {"color", "alpha", "solid"}.

    A literal "#RRGGBB" in place of a name is taken as is. "solid" is
    what KDE stores; when the token file gives none it is the colour
    drawn over bg.base.
    """
    if name.startswith("#"):
        rgb(name)
        return {"color": name.upper(), "alpha": 1.0, "solid": name.upper()}
    value = tokens["color"][name][mode]
    if isinstance(value, str):
        rgb(value)
        return {"color": value.upper(), "alpha": 1.0, "solid": value.upper()}
    alpha = float(value["alpha"])
    solid = value.get("solid")
    if solid is None:
        base = tokens["color"]["bg.base"][mode]
        solid = mix(base, value["color"], alpha)
    return {"color": value["color"].upper(), "alpha": alpha,
            "solid": solid.upper()}


def solid(tokens, name, mode):
    return colour(tokens, name, mode)["solid"]


def colour_names(tokens):
    return sorted(tokens["color"])


def grey(c):
    """The grey of the same brightness as '#RRGGBB' (Rec. 601 luma)."""
    r, g, b = rgb(c)
    y = 0.299 * r + 0.587 * g + 0.114 * b
    return hexstr((y, y, y))


def hsl(c):
    """'#RRGGBB' -> (hue, saturation, lightness), each 0..1."""
    r, g, b = (v / 255.0 for v in rgb(c))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    return h, s, l


def from_hsl(h, s, l):
    """A colour back from (hue, saturation, lightness), on 8 bits."""
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return hexstr((r * 255, g * 255, b * 255))


OPPOSITE = {"#FFFFFF": "#000000", "#000000": "#FFFFFF"}


def on_accent_text(tokens, accent, mode):
    """(text colour, hover target, hover amount, pressed target, pressed
    amount) for a filled accent.

    The text must hold its ratio on the accent, the hovered and the
    pressed shade together. White wins when it holds on the accent
    itself, then dark text; a shade that loses the text is moved back
    toward the accent, as far as needed, never past the accent. A pressed
    shade left with less than half its change goes the other way (white
    for black), and a hover left with less than half its change goes the
    pressed way at half the pressed change, so every state still shows.
    """
    rule = tokens["accent_rule"]
    on = rule["on_accent"]
    want = on["min_contrast"]
    if contrast(on["light"], accent) >= want:
        text = on["light"]
    elif contrast(on["dark"], accent) >= want:
        text = on["dark"]
    else:
        text = max((on["light"], on["dark"]), key=lambda c: contrast(c, accent))
    # an accent no text holds on: keep at least what the accent gives
    floor = min(want, contrast(text, accent))

    def back_off(toward, amount):
        while amount > 0 and contrast(text, mix(accent, toward, amount)) < floor:
            amount = max(0.0, round(amount - on["back_off_step"], 6))
        return amount

    hover, pressed = rule["hover"][mode], rule["pressed"][mode]
    pressed_toward = pressed["toward"]
    pressed_amount = back_off(pressed_toward, pressed["amount"])
    other = OPPOSITE.get(pressed_toward.upper())
    if pressed_amount < pressed["amount"] / 2 and other:
        flipped = back_off(other, pressed["amount"])
        if flipped >= pressed["amount"] / 2:
            pressed_toward, pressed_amount = other, flipped
    hover_toward = hover["toward"]
    hover_amount = back_off(hover_toward, hover["amount"])
    if (hover_amount < hover["amount"] / 2 and pressed_toward.upper() != hover_toward.upper()
            and pressed_amount > 0):
        hover_toward, hover_amount = pressed_toward, pressed_amount / 2
    elif pressed_toward.upper() == hover_toward.upper():
        # one way for both: hover sits halfway to pressed at most
        hover_amount = min(hover_amount, pressed_amount / 2)
    return text, hover_toward, hover_amount, pressed_toward, pressed_amount


def derive_accent(tokens, accent, mode):
    """The shades of a user-picked accent, by the rule of the token file.

    Used at run time for any accent; for the default accent the token
    file's own values win (they are tuned by eye).
    """
    rule = tokens["accent_rule"]
    base = solid(tokens, rule["text"]["on"], mode)
    on_accent, hover_toward, hover_amount, pressed_toward, pressed_amount = \
        on_accent_text(tokens, accent, mode)
    hover = mix(accent, hover_toward, hover_amount)
    pressed = mix(accent, pressed_toward, pressed_amount)
    text = accent
    toward = rule["text"][mode]["toward"]
    step = rule["text"]["step"]
    want = rule["text"][mode]["min_contrast"]
    t = 0.0
    while contrast(text, base) < want and t < 1.0:
        t = min(1.0, t + step)
        text = mix(accent, toward, t)
    dis = rule["disabled"]
    disabled = mix(solid(tokens, dis["over"], mode), accent, dis["alpha"])
    disabled = mix(disabled, grey(disabled), dis["desaturate"])
    return {"accent": accent.upper(), "accent.hover": hover, "accent.pressed": pressed,
            "accent.text": text, "accent.disabled": disabled,
            "text.onAccent": on_accent.upper()}


SELECTION_TINTS = ("selection.inactive", "selection.visited", "selection.negative",
                   "selection.neutral", "selection.positive")


def readable_ceiling(tokens, bg):
    """The best ratio ANY colour reaches on `bg`: white or the dark text.

    No tint can beat it, so it is the only honest floor on a background
    that nothing holds 4.5:1 on -- and the one that keeps a test from
    asking for the impossible.
    """
    on = tokens["accent_rule"]["on_accent"]
    return max(contrast(on["light"], bg), contrast(on["dark"], bg))


def tint_amount(tokens, name, mode):
    """How far the table moves the text on the accent toward the accent."""
    accent = solid(tokens, "accent", mode)
    text = solid(tokens, "text.onAccent", mode)
    want = rgb(solid(tokens, name, mode))
    a, t = rgb(accent), rgb(text)
    spans = [(w - x) / (y - x) for w, x, y in zip(want, t, a) if abs(y - x) >= 32]
    return sum(spans) / len(spans) if spans else 0.0


def selection_seed(tokens, accent, mode, name, on_accent):
    """Where a tint starts, before its lightness is corrected."""
    if tokens["accent_rule"]["selection"]["hue"][name] == "accent":
        return mix(on_accent, accent, tint_amount(tokens, name, mode))
    return solid(tokens, name, mode)


def to_contrast(seed, backgrounds, minimums, toward_light, step):
    """`seed` with its LIGHTNESS walked until it holds every minimum on
    its background, hue and saturation kept.

    The walk is what makes the ratio a guarantee rather than a hope: it
    stops at the first lightness that holds, so the tint keeps as much of
    its own colour as the ratio allows, and it ends at white (or black)
    when no lightness holds -- which is the readable ceiling's own case.
    """
    h, s, l = hsl(seed)
    end = 1.0 if toward_light else 0.0

    def holds(c):
        return all(contrast(c, bg) >= want - 1e-9
                   for bg, want in zip(backgrounds, minimums))

    if holds(seed):
        return seed
    steps = int(abs(end - l) / step) + 1
    for i in range(1, steps + 1):
        c = from_hsl(h, s, l + (end - l) * (i / float(steps)))
        if holds(c):
            return c
    return from_hsl(h, s, end)


def derive_selection(tokens, accent, mode, derived=None):
    """The five tinted foregrounds of a selected row, for any accent.

    Every one of them is text on the selection, so every one is held to
    the WCAG minimum on BOTH selection backgrounds -- the accent and its
    pressed shade, which is the alternate selected row.
    """
    rule = tokens["accent_rule"]["selection"]
    light = tokens["accent_rule"]["on_accent"]["light"]
    derived = derived or derive_accent(tokens, accent, mode)
    backgrounds = [derived[name] for name in rule["on"]]
    minimums = [min(rule["min_contrast"], readable_ceiling(tokens, bg))
                for bg in backgrounds]
    toward_light = derived["text.onAccent"].upper() == light.upper()
    return {name: to_contrast(
                selection_seed(tokens, accent, mode, name, derived["text.onAccent"]),
                backgrounds, minimums, toward_light, rule["step"])
            for name in SELECTION_TINTS}


def check_pairs(tokens):
    """[(mode, fg, bg, ratio, minimum)] for every pair below its minimum."""
    bad = []
    for mode in MODES:
        for fg, bg, minimum in tokens["contrast"]["pairs"]:
            ratio = contrast(solid(tokens, fg, mode), solid(tokens, bg, mode))
            if ratio < minimum:
                bad.append((mode, fg, bg, round(ratio, 2), minimum))
    return bad


# --- KDE colour schemes -----------------------------------------------

KDE_KEYS = (
    "BackgroundAlternate", "BackgroundNormal", "DecorationFocus",
    "DecorationHover", "ForegroundActive", "ForegroundInactive",
    "ForegroundLink", "ForegroundNegative", "ForegroundNeutral",
    "ForegroundNormal", "ForegroundPositive", "ForegroundVisited",
)
KDE_GROUPS = ("Button", "Complementary", "Header", "Header][Inactive",
              "Selection", "Tooltip", "View", "Window")
KDE_WM_KEYS = ("activeBackground", "activeBlend", "activeForeground",
               "inactiveBackground", "inactiveBlend", "inactiveForeground")


def kde_group(tokens, group):
    """Token name per key of a colour group, following "from"."""
    spec = tokens["kde"]["groups"][group]
    keys = dict(kde_group(tokens, spec["from"])[0]) if "from" in spec else {}
    mode = spec.get("mode")
    if "from" in spec and mode is None:
        mode = kde_group(tokens, spec["from"])[1]
    for k, v in spec.items():
        if k in KDE_KEYS:
            keys[k] = v
    return keys, mode


def kde_rgb(c):
    return "%d,%d,%d" % rgb(c)


def kde_value(tokens, v, mode):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return ("%g" % v)
    return kde_rgb(solid(tokens, v, mode))


def colors_file(tokens, mode):
    info = tokens["modes"][mode]
    out = ["# %s: the %s colours of Raye Linux." % (info["name"], mode),
           "# %s; edit the token file, not this one." % GENERATED, ""]
    for section in sorted(tokens["kde"]["effects"]):
        out.append("[%s]" % section)
        for k, v in sorted(tokens["kde"]["effects"][section].items()):
            out.append("%s=%s" % (k, kde_value(tokens, v, mode)))
        out.append("")
    for group in KDE_GROUPS:
        keys, group_mode = kde_group(tokens, group)
        missing = set(KDE_KEYS) - set(keys)
        if missing:
            raise ValueError("Colors:%s has no %s" % (group, ", ".join(sorted(missing))))
        out.append("[Colors:%s]" % group)
        for k in KDE_KEYS:
            out.append("%s=%s" % (k, kde_rgb(solid(tokens, keys[k], group_mode or mode))))
        out.append("")
    out.append("[General]")
    general = dict(tokens["kde"]["general"])
    general["ColorScheme"] = info["scheme"]
    general["Name"] = info["name"]
    general["Name[fr]"] = info["name_fr"]
    for k in sorted(general, key=lambda k: (k.lower(), k)):
        v = general[k]
        out.append("%s=%s" % (k, kde_value(tokens, v, mode) if not isinstance(v, str) else v))
    out += ["", "[KDE]", "contrast=%d" % tokens["kde"]["contrast"], "", "[WM]"]
    for k in KDE_WM_KEYS:
        out.append("%s=%s" % (k, kde_rgb(solid(tokens, tokens["kde"]["wm"][k], mode))))
    return "\n".join(out) + "\n"


# --- Konsole ----------------------------------------------------------

def konsole_file(tokens, mode):
    info = tokens["modes"][mode]
    term = tokens["terminal"][mode]
    words = {"night": "dark violet", "day": "light, violet ink"}[mode]
    out = ["# %s: %s, made for Raye Linux." % (info["name"], words),
           "# %s; edit the token file, not this one." % GENERATED, "",
           "[General]",
           "Description=%s" % info["name"],
           "Description[fr]=%s" % info["name_fr"],
           "Opacity=%g" % term["opacity"],
           "Blur=%s" % ("true" if term["blur"] else "false"),
           "Wallpaper=", ""]

    def entry(name, c):
        out.extend(["[%s]" % name, "Color=%s" % kde_rgb(c), ""])

    entry("Background", term["background"])
    entry("BackgroundIntense", term["background.intense"])
    entry("BackgroundFaint", term["background"])
    entry("Foreground", term["foreground"])
    entry("ForegroundIntense", term["foreground.intense"])
    entry("ForegroundFaint", term["foreground"])
    for i in range(8):
        entry("Color%d" % i, term["ansi"][i])
        entry("Color%dIntense" % i, term["ansi.intense"][i])
        entry("Color%dFaint" % i, term["ansi"][i])
    return "\n".join(out).rstrip("\n") + "\n"


# --- QML --------------------------------------------------------------

def camel(name):
    """'fill.control.hover' -> 'fillControlHover', 'text.onAccent' -> 'textOnAccent'."""
    parts = re.split(r"[.\-]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def qml_colour(c, alpha=1.0):
    r, g, b = rgb(c)
    if alpha >= 1.0:
        return '"#%02x%02x%02x"' % (r, g, b)
    return '"#%02x%02x%02x%02x"' % (int(round(alpha * 255)), r, g, b)


def qml_num(v):
    return ("%g" % v) if isinstance(v, float) else str(v)


