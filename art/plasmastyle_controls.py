def _pill_frame(svg, st, prefix, fill, pill):
    """A 4 px rounded tint whose left piece carries the 3 px accent pill.
    The corner tiles are 8 px, so in a 32 px row the stretched left piece
    (and its pill) is 16 px, Windows' size."""
    c = 8
    y0 = st.next(2 * c + 16)
    boxes = piece_boxes(0, y0, c, 16)
    for name in PIECES:
        x, y, w, h = boxes[name]
        parts = []
        if name in ("topleft", "topright", "bottomleft", "bottomright"):
            parts.append('<path d="%s" %s/>' % (corner_fill(x, y, c, 4, name), paint(*fill)))
        else:
            parts.append(rect(x, y, w, h, fill))
        if pill and name == "left":
            parts.append(rect(x, y, 3, h, (ACCENT, 1), rx=1.5))
        svg.add(prefix + name, parts, (x, y, w, h))


