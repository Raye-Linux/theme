#!/usr/bin/env python3
#
# The controls of the Raye Plasma style (desktoptheme/raye/widgets/):
# buttons, text fields, check boxes, radio buttons, switches, sliders,
# progress bars, scroll bars, list and view items, tabs, the busy ring,
# the clock face and the smaller pieces the shell draws from the style.
#
# Windows 11 sizes (theming spec 1.9, 3.3): 32 px buttons with 4 px
# corners, a 40x20 switch with a 12 px knob, a 20 px slider thumb with an
# accent centre on a 4 px track, 20 px radio buttons with Windows'
# inverted dot, a 3 px progress bar on a 1 px rail, thin scroll bars,
# list rows with a tint and a 3 px accent pill. Element names are
# Plasma's own (the stock style uses them); every drawing is Raye's and
# takes its colours from the colour scheme (ColorScheme-* classes), so
# Raye Night and Raye Day both work. The surfaces (popups, tooltips, the
# taskbar) are art/plasmastyle.py; this file reuses its helpers.
#
#   python3 art/plasmastyle_controls.py           write the files
#   python3 art/plasmastyle_controls.py --check   exit 1 if a file is not current

