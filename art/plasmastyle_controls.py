def lineedit():
    """widgets/lineedit: the field ("base"), hover over it, and focus:
    Windows' 2 px accent line inside the bottom edge."""
    svg = Svg()
    st = ps.Stack()
    pad = (6, 6, 6, 10)
    frame_block(svg, st, "base-", 4, [(BUTTON, 1)], line=STROKE, corner=4, pad=pad, compose=True)
    frame_block(svg, st, "hover-", 4, [SUBTLE_PRESSED], corner=4, pad=pad)
    for prefix in ("focus-", "focusframe-"):
        # the focused field goes to the darkest fill, with the accent line
        c = 4
        y = st.next(2 * c + 16)
        band_frame(svg, prefix, 0, y, 4, ("#000000", 0.12), band=(ACCENT, 1), band_sides=("bottom",), width=2,
                   corner=c)
        margins(svg, prefix, st.next(16), *pad)
    svg.hint("hint-focus-over-base", 0, st.next(4), 4, 4)
    return svg


