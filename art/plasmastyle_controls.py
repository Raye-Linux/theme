def clock():
    """widgets/clock: the analog clock. The face is 100 x 100; each hand is
    an element as tall as the face, centred on it, so the hand turns about
    the middle of its element."""
    svg = Svg()
    face = [circle(50, 50, 49, (BG, 0.9)), ring(50, 50, 50, 1, STROKE)]
    for i in range(12):
        a = math.radians(i * 30)
        long_tick = i % 3 == 0
        r1, r2 = (39, 45) if long_tick else (42, 45)
        x1, y1 = 50 + r1 * math.sin(a), 50 - r1 * math.cos(a)
        x2, y2 = 50 + r2 * math.sin(a), 50 - r2 * math.cos(a)
        face.append(stroke_path("M%s,%s L%s,%s" % (num(x1), num(y1), num(x2), num(y2)), TEXT,
                                0.9 if long_tick else 0.45, width=2 if long_tick else 1.2))
    svg.add("ClockFace", face, (0, 0, 100, 100))
    hands = (("HourHand", 26, 3.5, TEXT, 1), ("MinuteHand", 38, 2.5, TEXT, 1), ("SecondHand", 42, 1.2, ACCENT, 1))
    x = 106
    for name, length, width, cls, opacity in hands:
        cx = x + 3
        hand = stroke_path("M%s,%s L%s,%s" % (num(cx), num(50 + 4), num(cx), num(50 - length)), cls, opacity,
                           width=width)
        svg.add(name, [hand], (x, 0, 6, 100))
        shadow_hand = stroke_path("M%s,%s L%s,%s" % (num(cx + 8), num(50 + 4), num(cx + 8), num(50 - length)),
                                  "#000000", 0.18, width=width)
        svg.add(name + "Shadow", [shadow_hand], (x + 8, 0, 6, 100))
        x += 18
    svg.add("HandCenterScrew", [circle(x + 4, 4, 3.5, (ACCENT, 1)), circle(x + 4, 4, 1.2, (BG, 1))], (x, 0, 8, 8))
    svg.add("Glass", [], (x + 12, 0, 100, 100))
    svg.hint("hint-hands-shadow-offset-to-south", x + 116, 0, 1, 1)
    return svg


