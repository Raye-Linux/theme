# the scheme classes this file paints with: the ones of plasmastyle.py
# plus the text on the accent (the values are what an SVG viewer shows:
# Raye Night; Plasma replaces them with the scheme's)
SCHEME = dict(ps.SCHEME, **{"ColorScheme-HighlightedText": "#ffffff"})


class Svg(ps.Svg):
    """plasmastyle's Svg, writing this file's colour classes."""

    def text(self):
        if "hint-stretch-borders" not in self.names:
            self.hint("hint-stretch-borders", self.width + 2, 0, 4, 4)
        style = "".join(".%s { color: %s; }" % (k, v) for k, v in SCHEME.items())
        return ('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- Generated by art/plasmastyle_controls.py; edit that file, not this one. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="%s" height="%s" viewBox="0 0 %s %s">\n'
                '<defs><style type="text/css" id="current-color-scheme">%s</style>%s</defs>\n%s\n</svg>\n'
                % (num(self.width), num(self.height), num(self.width), num(self.height),
                   style, "".join(self.defs), "\n".join(self.body)))

TEXT = "ColorScheme-Text"
BG = "ColorScheme-Background"
BUTTON = "ColorScheme-ButtonBackground"
ACCENT = "ColorScheme-Highlight"
ON_ACCENT = "ColorScheme-HighlightedText"

# token roles as scheme colour + alpha (theming spec 3.1, night values)
STROKE = (TEXT, 0.10)          # stroke.control
STROKE_STRONG = (TEXT, 0.55)   # stroke.strong (checkbox, radio, switch rest)
SUBTLE_HOVER = (TEXT, 0.06)    # fill.subtle.hover
SUBTLE_PRESSED = (TEXT, 0.04)  # fill.subtle.pressed
SELECTED = (ACCENT, 0.18)      # fill.subtle.selected
DIVIDER = (TEXT, 0.08)         # stroke.divider
GLOW = "#c040ff"               # the Raye glow, fixed in both modes


class Row:
    """Places elements left to right, wrapping into rows."""

    def __init__(self, width=480):
        self.x = 0
        self.y = 0
        self.row_h = 0
        self.width = width

    def place(self, w, h):
        if self.x + w > self.width and self.x > 0:
            self.x = 0
            self.y += self.row_h + 6
            self.row_h = 0
        x, y = self.x, self.y
        self.x += w + 6
        self.row_h = max(self.row_h, h)
        return x, y

    def newline(self):
        if self.x > 0:
            self.x = 0
            self.y += self.row_h + 6
            self.row_h = 0
        return self.y


def rect(x, y, w, h, fill, rx=0):
    r = (' rx="%s"' % num(rx)) if rx else ""
    return '<rect x="%s" y="%s" width="%s" height="%s"%s %s/>' % (num(x), num(y), num(w), num(h), r, paint(*fill))


def circle(cx, cy, r, fill):
    return '<circle cx="%s" cy="%s" r="%s" %s/>' % (num(cx), num(cy), num(r), paint(*fill))


def ring(cx, cy, r, width, fill):
    """A ring of the given width whose outer edge is at r."""
    inner = max(r - width, 0)
    return ('<path fill-rule="evenodd" d="M%s,%s a%s,%s 0 1 0 %s,0 a%s,%s 0 1 0 -%s,0 Z '
            'M%s,%s a%s,%s 0 1 0 %s,0 a%s,%s 0 1 0 -%s,0 Z" %s/>'
            % (num(cx - r), num(cy), num(r), num(r), num(2 * r), num(r), num(r), num(2 * r),
               num(cx - inner), num(cy), num(inner), num(inner), num(2 * inner), num(inner), num(inner),
               num(2 * inner), paint(*fill)))


def stroke_path(d, cls, opacity, width=1.5, cap="round"):
    """A stroked line in a scheme colour."""
    if cls.startswith("#"):
        colour = 'stroke="%s"' % cls
    else:
        colour = 'stroke="currentColor" class="%s"' % cls
    return ('<path d="%s" fill="none" %s stroke-opacity="%s" stroke-width="%s" stroke-linecap="%s" '
            'stroke-linejoin="round"/>' % (d, colour, num(opacity), num(width), cap))


def element(svg, row, name, w, h, parts_at):
    """A named element of w x h; parts_at(x, y) returns its drawing."""
    x, y = row.place(w, h)
    svg.add(name, parts_at(x, y), (x, y, w, h))
    return x, y


def hint(svg, row, name, w, h):
    x, y = row.place(max(w, 1), max(h, 1))
    svg.hint(name, x, y, max(w, 0.001), max(h, 0.001))


def band_frame(svg, prefix, x0, y0, radius, fill, band=None, band_sides=SIDES, width=1, corner=None,
               middle=16):
    """Nine pieces: a fill (or None) and a band of `width` px on band_sides.

    Like ps.frame, but the band may be wider than 1 px (focus rings, the
    focused text field's accent line)."""
    c = corner if corner is not None else max(radius, width, 1)
    boxes = piece_boxes(x0, y0, c, middle)
    for name in PIECES:
        x, y, w, h = boxes[name]
        parts = []
        is_corner = name in ("topleft", "topright", "bottomleft", "bottomright")
        if fill is not None:
            if is_corner:
                parts.append('<path d="%s" %s/>' % (corner_fill(x, y, c, radius, name), paint(*fill)))
            else:
                parts.append(rect(x, y, w, h, fill))
        if band is not None:
            parts += _band(name, x, y, w, h, c, radius, band, band_sides, width)
        svg.add(prefix + name, parts, (x, y, w, h))
    return 2 * c + middle, 2 * c + middle


def _band(name, x, y, w, h, c, radius, band, sides, width):
    attrs = paint(*band)
    corners = {"topleft": ("top", "left"), "topright": ("top", "right"),
               "bottomleft": ("bottom", "left"), "bottomright": ("bottom", "right")}
    out = []
    if name in corners:
        a, b = corners[name]
        if a in sides and b in sides:
            ix = x if "right" in name else x + width
            iy = y if "bottom" in name else y + width
            inner = corner_fill(ix, iy, c - width, max(radius - width, 0), name)
            out.append('<path fill-rule="evenodd" d="%s %s" %s/>' % (corner_fill(x, y, c, radius, name), inner, attrs))
        else:
            for s in (a, b):
                if s in sides:
                    out.append(_edge(s, x, y, w, h, width, attrs))
        return out
    if name in sides:
        out.append(_edge(name, x, y, w, h, width, attrs))
    return out


def _edge(side, x, y, w, h, width, attrs):
    if side == "top":
        box = (x, y, w, width)
    elif side == "bottom":
        box = (x, y + h - width, w, width)
    elif side == "left":
        box = (x, y, width, h)
    else:
        box = (x + w - width, y, width, h)
    return '<rect x="%s" y="%s" width="%s" height="%s" %s/>' % (num(box[0]), num(box[1]), num(box[2]), num(box[3]), attrs)


def margins(svg, prefix, y, top, right, bottom, left, kind="margin", x=0):
    return ps.margins(svg, prefix, x, y, top, right, bottom, left, kind)


def frame_block(svg, stack, prefix, radius, fill, line=None, sides=SIDES, mask=False, corner=None,
                pad=None, compose=False):
    """A 1 px-outlined frame from plasmastyle, plus its margins."""
    c = corner if corner is not None else max(radius, 1)
    ps.frame(svg, prefix, 0, stack.next(2 * c + 16), radius, fill, line=line, line_sides=sides,
             corner=corner, mask=mask)
    if pad is not None:
        margins(svg, prefix, stack.next(16), *pad)
    if compose:
        svg.hint(prefix + "hint-compose-over-border", 40, stack.next(4), 4, 4)


def ring_block(svg, stack, prefix, radius, cls, width=2, pad=None):
    """A keyboard focus ring: 2 px of text colour along the edge."""
    c = max(radius, width, 1)
    band_frame(svg, prefix, 0, stack.next(2 * c + 16), radius, None, band=(cls, 1.0), width=width)
    if pad is not None:
        margins(svg, prefix, stack.next(16), *pad)


def empty_frame(svg, stack, prefix, pad=(0, 0, 0, 0)):
    """Nine transparent pieces: the element exists but draws nothing."""
    ps.frame(svg, prefix, 0, stack.next(1 + 16 + 1), 0, (TEXT, 0), corner=1, mask=False)
    margins(svg, prefix, stack.next(16), *pad)


