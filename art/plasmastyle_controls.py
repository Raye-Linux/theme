def arrows():
    svg = Svg()
    row = Row()
    paths = {
        "up-arrow": "M%(a)s,%(c)s L8,%(b)s L%(d)s,%(c)s",
        "down-arrow": "M%(a)s,%(b)s L8,%(c)s L%(d)s,%(b)s",
    }
    def chevron(x, y, kind):
        if kind == "up-arrow":
            pts = ((4, 10), (8, 6), (12, 10))
        elif kind == "down-arrow":
            pts = ((4, 6), (8, 10), (12, 6))
        elif kind == "left-arrow":
            pts = ((10, 4), (6, 8), (10, 12))
