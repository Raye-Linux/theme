def render_all():
    return {path: make().text() for path, make in FILES.items()}


def stale():
    old = []
    for path, text in render_all().items():
        full = os.path.join(OUT, path)
        try:
            with open(full, encoding="utf-8") as f:
                if f.read() == text:
                    continue
        except FileNotFoundError:
            pass
        old.append(path)
    return sorted(old)


def main(argv):
    if "--check" in argv[1:]:
        old = stale()
        for path in old:
            print("not current: desktoptheme/raye/" + path)
        return 1 if old else 0
    for path, text in sorted(render_all().items()):
        full = os.path.join(OUT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as f:
            f.write(text)
        print("desktoptheme/raye/" + path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
