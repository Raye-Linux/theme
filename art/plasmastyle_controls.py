# 32 px tall with body text: 7 px above and below, 11 px left and right
BUTTON_PAD = (7, 11, 7, 11)


def button():
    """widgets/button: the push button and the tool (flat) button states.
    Plasma also draws check boxes from button "normal" + checkmarks."""
    svg = Svg()
    st = ps.Stack()
    # rest: control fill, 1 px stroke, a slightly stronger bottom row
    frame_block(svg, st, "normal-", 4, [(BUTTON, 1)], line=STROKE, mask=True, corner=4,
                pad=BUTTON_PAD, compose=True)
    # pressed (and Plasma's "highlighted" buttons): a step darker, text dims in QML
    frame_block(svg, st, "pressed-", 4, [(BUTTON, 1), ("#000000", 0.10)], line=(TEXT, 0.08),
                corner=4, pad=BUTTON_PAD, compose=True)
    # hover: drawn over "normal"
    frame_block(svg, st, "hover-", 4, [SUBTLE_PRESSED], corner=4, pad=BUTTON_PAD)
    # keyboard focus: the Windows ring along the edge
    ring_block(svg, st, "focus-", 4, TEXT, pad=BUTTON_PAD)
    # flat buttons in toolbars, the taskbar and popups
    frame_block(svg, st, "toolbutton-hover-", 4, [SUBTLE_HOVER], corner=4, pad=BUTTON_PAD)
    frame_block(svg, st, "toolbutton-pressed-", 4, [SUBTLE_PRESSED], corner=4, pad=BUTTON_PAD)
    ring_block(svg, st, "toolbutton-focus-", 4, TEXT, pad=BUTTON_PAD)
    # Windows buttons cast no shadow: present, but empty
    ps.frame(svg, "shadow-", 0, st.next(18), 0, (TEXT, 0), corner=1, mask=False)
    margins(svg, "shadow-", st.next(16), 0, 0, 0, 0)
    return svg


def actionbutton():
    """widgets/actionbutton: small round buttons (overlays on icons)."""
    svg = Svg()
    row = Row()
    for size in (None, 16, 22, 24):
        s = size or 24
        prefix = "%d-%d-" % (s, s) if size else ""
        r = s / 2
        element(svg, row, prefix + "normal", s, s, lambda x, y: [circle(x + r, y + r, r - 0.5, (BUTTON, 1)),
                                                                   ring(x + r, y + r, r, 1, STROKE)])
        element(svg, row, prefix + "hover", s, s, lambda x, y: [circle(x + r, y + r, r - 0.5, SUBTLE_HOVER)])
        element(svg, row, prefix + "pressed", s, s, lambda x, y: [circle(x + r, y + r, r - 0.5, (BUTTON, 1)),
                                                                    circle(x + r, y + r, r - 0.5, ("#000000", 0.1))])
        element(svg, row, prefix + "focus", s, s, lambda x, y: [ring(x + r, y + r, r, 2, (TEXT, 1))])
        row.newline()
    return svg


