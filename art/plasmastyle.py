#!/usr/bin/env python3
#
# The surfaces of the Raye Plasma style (desktoptheme/raye): popups and
# dialogs, tooltips, the taskbar background, desktop widget backgrounds,
# frames and the header and footer bars of popups.
#
# Plasma draws a frame from nine named pieces (corners, edges, centre):
# each piece is rendered on its own and the edges and centre are
# stretched. The element names are Plasma's own; the drawing is Raye's.
# Colours come from the colour scheme through the ColorScheme-* classes,
# so Raye Night and Raye Day repaint every piece. Only the shadows are a
# fixed colour, because a shadow is dark in both.
#
# Each surface comes in the variants Plasma picks from:
#   translucent/  the compositor blurs behind it: acrylic
#   (top level)   compositing on but no blur ("Transparency effects" off)
#   solid/        an applet that asked for an opaque background
#   opaque/       no compositing at all: no shadow, no alpha
#
# The helpers (Svg, frame, shadow, hints) are shared with the controls
# of the style (art/plasmastyle_controls.py).
#
#   python3 art/plasmastyle.py           write the files
#   python3 art/plasmastyle.py --check   exit 1 if a file is not current

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "desktoptheme", "raye")
TOKENS = os.path.join(ROOT, "tokens", "raye-tokens.json")

PIECES = ("topleft", "top", "topright", "left", "center", "right",
          "bottomleft", "bottom", "bottomright")
SIDES = ("top", "right", "bottom", "left")

# the colour classes Plasma fills in from the scheme (the values written
# here are only what an SVG viewer shows: Raye Night)
SCHEME = {
    "ColorScheme-Text": "#f1f0f4",
    "ColorScheme-Background": "#141318",
    "ColorScheme-Highlight": "#7b3cff",
    "ColorScheme-ViewBackground": "#1b1a1f",
    "ColorScheme-ButtonBackground": "#26252b",
}
SHADOW = "#000000"


def load_tokens(path=TOKENS):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def num(v):
    """A coordinate without trailing zeros."""
    v = round(float(v), 3)
    return ("%d" % v) if v == int(v) else ("%g" % v)


class Svg:
    """An SVG made of named elements, laid out on a canvas that grows."""

    def __init__(self):
        self.body = []
        self.defs = []
        self.width = 0
        self.height = 0
        self.names = []
        self._grad = 0

    def grow(self, x, y):
        self.width = max(self.width, x)
        self.height = max(self.height, y)

    def add(self, name, parts, box):
        """A named group; box = (x, y, w, h) sets its size, drawn or not."""
        assert name not in self.names, name
        self.names.append(name)
        x, y, w, h = box
        self.grow(x + w, y + h)
        sizer = ('<rect x="%s" y="%s" width="%s" height="%s" fill="#000" fill-opacity="0"/>'
                 % (num(x), num(y), num(w), num(h)))
        self.body.append('<g id="%s">%s%s</g>' % (name, sizer, "".join(parts)))

    def hint(self, name, x, y, w, h):
        """A hint: a plain rect, only its size counts."""
        assert name not in self.names, name
        self.names.append(name)
        self.grow(x + w, y + h)
        self.body.append('<rect id="%s" x="%s" y="%s" width="%s" height="%s" fill="#ff00ff"/>'
                         % (name, num(x), num(y), num(w), num(h)))

    def gradient(self, kind, attrs, stops):
        self._grad += 1
        gid = "raye-gradient-%d" % self._grad
        s = "".join('<stop offset="%s" stop-color="%s" stop-opacity="%s"/>' % (num(o), c, num(a))
                    for o, c, a in stops)
        self.defs.append('<%s id="%s" gradientUnits="userSpaceOnUse" %s>%s</%s>'
                         % (kind, gid, attrs, s, kind))
        return "url(#%s)" % gid

    def text(self):
        # edges are stretched, never tiled: a tiled 1 px outline shows
        # seams at every tile
        if "hint-stretch-borders" not in self.names:
            self.hint("hint-stretch-borders", self.width + 2, 0, 4, 4)
        style = "".join(".%s { color: %s; }" % (k, v) for k, v in SCHEME.items())
        return ('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- Generated by art/plasmastyle.py; edit that file, not this one. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="%s" height="%s" viewBox="0 0 %s %s">\n'
                '<defs><style type="text/css" id="current-color-scheme">%s</style>%s</defs>\n%s\n</svg>\n'
                % (num(self.width), num(self.height), num(self.width), num(self.height),
                   style, "".join(self.defs), "\n".join(self.body)))


def paint(cls, opacity):
    """fill attributes: a scheme class at an opacity, or a fixed colour."""
    if cls.startswith("#"):
        return 'fill="%s" fill-opacity="%s"' % (cls, num(opacity))
    return 'fill="currentColor" class="%s" fill-opacity="%s"' % (cls, num(opacity))


def corner_fill(x, y, c, r, where):
    """A c x c tile whose outer corner is rounded by r (r <= c)."""
    if r <= 0:
        return "M%s,%s h%s v%s h-%s Z" % (num(x), num(y), num(c), num(c), num(c))
    if where == "topleft":
        return ("M%s,%s V%s A%s,%s 0 0 1 %s,%s H%s V%s Z"
                % (num(x), num(y + c), num(y + r), num(r), num(r), num(x + r), num(y),
                   num(x + c), num(y + c)))
    if where == "topright":
        return ("M%s,%s H%s A%s,%s 0 0 1 %s,%s V%s H%s Z"
                % (num(x), num(y), num(x + c - r), num(r), num(r), num(x + c), num(y + r),
                   num(y + c), num(x)))
    if where == "bottomleft":
        return ("M%s,%s H%s V%s H%s A%s,%s 0 0 1 %s,%s Z"
                % (num(x), num(y), num(x + c), num(y + c), num(x + r), num(r), num(r),
                   num(x), num(y + c - r)))
    return ("M%s,%s H%s V%s A%s,%s 0 0 1 %s,%s H%s Z"
            % (num(x), num(y), num(x + c), num(y + c - r), num(r), num(r), num(x + c - r),
               num(y + c), num(x)))


def piece_boxes(x0, y0, c, m):
    """Where the nine pieces of a frame go: corner tiles c, middle m."""
    return {
        "topleft": (x0, y0, c, c), "top": (x0 + c, y0, m, c),
        "topright": (x0 + c + m, y0, c, c),
        "left": (x0, y0 + c, c, m), "center": (x0 + c, y0 + c, m, m),
        "right": (x0 + c + m, y0 + c, c, m),
        "bottomleft": (x0, y0 + c + m, c, c), "bottom": (x0 + c, y0 + c + m, m, c),
        "bottomright": (x0 + c + m, y0 + c + m, c, c),
    }


def frame(svg, prefix, x0, y0, radius, fill, line=None, line_sides=SIDES, corner=None,
          middle=16, mask=True):
    """The nine pieces of a frame.

    fill: (class or colour, opacity), or a list of them painted in
    order; line: (class, opacity) for a 1 px
    outline on line_sides, or None. Pieces are named prefix + piece and,
    with mask, "mask-" + prefix + piece (the shape the compositor blurs
    behind, and the window shape without compositing).
    Returns the width and height used.
    """
    c = corner if corner is not None else max(radius, 1)
    fills = fill if isinstance(fill, list) else [fill]
    boxes = piece_boxes(x0, y0, c, middle)
    for name in PIECES:
        x, y, w, h = boxes[name]
        parts = []
        rounded = name in ("topleft", "topright", "bottomleft", "bottomright")
        for f in fills:
            if rounded:
                parts.append('<path d="%s" %s/>' % (corner_fill(x, y, c, radius, name), paint(*f)))
            else:
                parts.append('<rect x="%s" y="%s" width="%s" height="%s" %s/>'
                             % (num(x), num(y), num(w), num(h), paint(*f)))
        if line:
            parts += outline(name, x, y, w, h, c, radius, line, line_sides)
        svg.add(prefix + name, parts, (x, y, w, h))
    used_w = 2 * c + middle
    if mask:
        mx = x0 + used_w + 4
        boxes = piece_boxes(mx, y0, c, middle)
        for name in PIECES:
            x, y, w, h = boxes[name]
            if name in ("topleft", "topright", "bottomleft", "bottomright"):
                part = '<path d="%s" fill="#000"/>' % corner_fill(x, y, c, radius, name)
            else:
                part = '<rect x="%s" y="%s" width="%s" height="%s" fill="#000"/>' % (
                    num(x), num(y), num(w), num(h))
            svg.add("mask-" + prefix + name, [part], (x, y, w, h))
        used_w = 2 * used_w + 4
    return used_w, 2 * c + middle


def outline(name, x, y, w, h, c, radius, line, sides):
    """The 1 px outline of one piece, on the outer side(s) of the frame.
    Drawn as a filled band, not a stroke: a stroke would make the piece
    half a pixel larger than its tile, and Plasma sizes pieces by their
    bounds."""
    cls, opacity = line
    attrs = paint(cls, opacity)
    out = []
    corners = {"topleft": ("top", "left"), "topright": ("top", "right"),
               "bottomleft": ("bottom", "left"), "bottomright": ("bottom", "right")}
    if name in corners:
        a, b = corners[name]
        if a in sides and b in sides:
            ix = x if "right" in name else x + 1
            iy = y if "bottom" in name else y + 1
            inner = corner_fill(ix, iy, c - 1, max(radius - 1, 0), name)
            out.append('<path fill-rule="evenodd" d="%s %s" %s/>'
                       % (corner_fill(x, y, c, radius, name), inner, attrs))
        else:
            # one side only: a straight band along it
            for s in (a, b):
                if s in sides:
                    out.append(edge_line(s, x, y, w, h, attrs))
        return out
    if name in sides:
        out.append(edge_line(name, x, y, w, h, attrs))
    return out


def edge_line(side, x, y, w, h, attrs):
    """A 1 px band along one side of a w x h tile."""
    if side == "top":
        box = (x, y, w, 1)
    elif side == "bottom":
        box = (x, y + h - 1, w, 1)
    elif side == "left":
        box = (x, y, 1, h)
    else:
        box = (x + w - 1, y, 1, h)
    return '<rect x="%s" y="%s" width="%s" height="%s" %s/>' % (
        num(box[0]), num(box[1]), num(box[2]), num(box[3]), attrs)


def margins(svg, prefix, x0, y0, top, right, bottom, left, kind="margin"):
    """hint-<side>-margin (or -inset): how far content stays from the edge."""
    svg.hint("%shint-top-%s" % (prefix, kind), x0, y0, 4, max(top, 0.001))
    svg.hint("%shint-bottom-%s" % (prefix, kind), x0 + 6, y0, 4, max(bottom, 0.001))
    svg.hint("%shint-left-%s" % (prefix, kind), x0 + 12, y0, max(left, 0.001), 4)
    svg.hint("%shint-right-%s" % (prefix, kind), x0 + 12, y0 + 6, max(right, 0.001), 4)
    return max(top, bottom, 10) + 2


# Shadow falloff: the opacity at the frame edge, then a soft Gaussian-like
# fade to nothing at the end of the shadow.
FALLOFF = ((0, 1.0), (0.18, 0.62), (0.4, 0.3), (0.65, 0.1), (1, 0))


def shadow(svg, x0, y0, extents, opacity, radius, under):
    """shadow-* pieces around a frame: extents = (top, right, bottom, left)
    px outside the frame, under = px of each piece that lies under the
    frame (transparent). Plus the shadow-hint margins and insets."""
    top, right, bottom, left = extents
    m = 16
    tiles = {
        "topleft": (x0, y0, left + under, top + under),
        "top": (x0 + left + under, y0, m, top + under),
        "topright": (x0 + left + under + m, y0, right + under, top + under),
        "left": (x0, y0 + top + under, left + under, m),
        "center": (x0 + left + under, y0 + top + under, m, m),
        "right": (x0 + left + under + m, y0 + top + under, right + under, m),
        "bottomleft": (x0, y0 + top + under + m, left + under, bottom + under),
        "bottom": (x0 + left + under, y0 + top + under + m, m, bottom + under),
        "bottomright": (x0 + left + under + m, y0 + top + under + m, right + under, bottom + under),
    }
    # the frame's rectangle inside the shadow tiles
    fx0, fy0 = x0 + left, y0 + top
    fx1, fy1 = x0 + left + 2 * under + m, y0 + top + 2 * under + m

    def stops():
        return [(o, SHADOW, opacity * a) for o, a in FALLOFF]

    for name in PIECES:
        x, y, w, h = tiles[name]
        parts = []
        if name == "center":
            svg.add("shadow-center", parts, (x, y, w, h))
            continue
        # only outside the frame: under a see-through popup a shadow
        # would darken it
        if name == "top":
            g = svg.gradient("linearGradient", 'x1="0" y1="%s" x2="0" y2="%s"'
                             % (num(fy0), num(y0)), stops())
            rect = (x, y0, w, top)
        elif name == "bottom":
            g = svg.gradient("linearGradient", 'x1="0" y1="%s" x2="0" y2="%s"'
                             % (num(fy1), num(fy1 + bottom)), stops())
            rect = (x, fy1, w, bottom)
        elif name == "left":
            g = svg.gradient("linearGradient", 'x1="%s" y1="0" x2="%s" y2="0"'
                             % (num(fx0), num(x0)), stops())
            rect = (x0, y, left, h)
        elif name == "right":
            g = svg.gradient("linearGradient", 'x1="%s" y1="0" x2="%s" y2="0"'
                             % (num(fx1), num(fx1 + right)), stops())
            rect = (fx1, y, right, h)
        if name in ("top", "bottom", "left", "right"):
            parts.append('<rect x="%s" y="%s" width="%s" height="%s" fill="%s"/>'
                         % (num(rect[0]), num(rect[1]), num(rect[2]), num(rect[3]), g))
        else:
            # a corner: an elliptic fade around the frame's rounded
            # corner, with the frame's own corner cut out of it
            cx = fx0 + radius if "left" in name else fx1 - radius
            cy = fy0 + radius if "top" in name else fy1 - radius
            rx = (left if "left" in name else right) + radius
            ry = (top if "top" in name else bottom) + radius
            k = radius / max(rx, ry)
            g = svg.gradient("radialGradient",
                             'cx="0" cy="0" r="1" gradientTransform="translate(%s %s) scale(%s %s)"'
                             % (num(cx), num(cy), num(rx), num(ry)),
                             [(k + o * (1 - k), c, a) for o, c, a in stops()])
            hx = fx0 if "left" in name else fx1 - under
            hy = fy0 if "top" in name else fy1 - under
            hole = corner_fill(hx, hy, under, radius, name)
            parts.append('<path fill-rule="evenodd" d="M%s,%s h%s v%s h-%s Z %s" fill="%s"/>'
                         % (num(x), num(y), num(w), num(h), num(w), hole, g))
        svg.add("shadow-" + name, parts, (x, y, w, h))
    hx = x0 + left + right + 2 * under + m + 6
    margins(svg, "shadow-", hx, y0, top, right, bottom, left)
    margins(svg, "shadow-", hx + 30, y0, top, right, bottom, left, kind="inset")
    return left + right + 2 * under + m + 70, top + bottom + 2 * under + m


class Stack:
    """Places blocks one under the other."""

    def __init__(self):
        self.y = 0

    def next(self, h):
        y = self.y
        self.y += h + 6
        return y


# --- the surfaces -----------------------------------------------------------

def alphas(tokens):
    color = tokens["color"]
    acrylic = min(color["acrylic.tint"]["night"]["alpha"], color["acrylic.tint"]["day"]["alpha"])
    taskbar = color["acrylic.taskbar"]["night"]["alpha"]
    return acrylic, taskbar


def flyout_shadow(tokens):
    """The menu/flyout shadow, between its Night and Day strength."""
    blur, dy, night = tokens["elevation"]["flyout"]["night"]
    day = tokens["elevation"]["flyout"]["day"][2]
    top = max(blur - dy, 4)
    return (top, blur, blur + dy, blur), round((night + day) / 2, 3)


def tooltip_shadow(tokens):
    blur, dy, night = tokens["elevation"]["tooltip"]["night"]
    day = tokens["elevation"]["tooltip"]["day"][2]
    return (max(blur - dy, 2), blur, blur + dy, blur), round((night + day) / 2, 3)


OUTLINE = ("ColorScheme-Text", 0.1)


def surface(variant, radius, fill_opacity, tokens, shadows, content, line=OUTLINE,
            mask=True):
    """A popup-like surface: frame + mask + shadows + content margins.
    The opaque variant has no insets: nothing is drawn around it."""
    svg = Svg()
    stack = Stack()
    y = stack.next(2 * max(radius, 1) + 16)
    frame(svg, "", 0, y, radius, ("ColorScheme-Background", fill_opacity), line=line, mask=mask)
    hy = stack.next(16)
    margins(svg, "", 0, hy, *content)
    if variant != "opaque":
        margins(svg, "", 40, hy, 0, 0, 0, 0, kind="inset")
    if shadows:
        extents, opacity = shadows
        _, h = shadow(svg, 0, stack.y, extents, opacity, radius, max(radius, 1))
        stack.next(h)
    return svg


def dialogs(tokens):
    acrylic, _ = alphas(tokens)
    r = tokens["radius"]["overlay"]
    sh = flyout_shadow(tokens)
    # what a popup's content keeps from the edge: Windows' flyout padding
    pad = (tokens["size"]["menu.padding"],) * 4
    return {
        "translucent/dialogs/background.svg": surface("translucent", r, acrylic, tokens, sh, pad),
        "dialogs/background.svg": surface("plain", r, 1, tokens, sh, pad),
        "solid/dialogs/background.svg": surface("solid", r, 1, tokens, sh, pad),
        "opaque/dialogs/background.svg": surface("opaque", r, 1, tokens, None, pad),
    }


def tooltips(tokens):
    acrylic, _ = alphas(tokens)
    r = tokens["radius"]["tooltip"]
    sh = tooltip_shadow(tokens)
    # Windows' tooltip padding is 8,5,8,7 around Caption text; Plasma's
    # tooltips add their own spacing inside, so keep the frame's small
    pad = (4, 6, 4, 6)
    return {
        "translucent/widgets/tooltip.svg": surface("translucent", r, acrylic, tokens, sh, pad),
        "widgets/tooltip.svg": surface("plain", r, 1, tokens, sh, pad),
        "solid/widgets/tooltip.svg": surface("solid", r, 1, tokens, sh, pad),
        "opaque/widgets/tooltip.svg": surface("opaque", r, 1, tokens, None, pad),
    }


def widget_backgrounds(tokens):
    """Backgrounds of widgets placed on the desktop: cards on the
    wallpaper, with a soft shadow."""
    acrylic, _ = alphas(tokens)
    r = tokens["radius"]["overlay"]
    sh = flyout_shadow(tokens)
    pad = (12, 12, 12, 12)
    out = {
        "translucent/widgets/background.svg": surface("translucent", r, acrylic, tokens, sh, pad,
                                                      mask=False),
        "widgets/background.svg": surface("plain", r, 1, tokens, sh, pad, mask=False),
        "solid/widgets/background.svg": surface("solid", r, 1, tokens, sh, pad),
    }
    # a tool button pressed on such a widget
    for path in ("translucent/widgets/background.svg", "widgets/background.svg"):
        svg = out[path]
        svg.add("toolbutton-pressed-center",
                ['<rect x="0" y="%s" width="16" height="16" %s/>'
                 % (num(svg.height + 6), paint("ColorScheme-Text", 0.06))],
                (0, svg.height + 6, 16, 16))
    return out


def translucent_background(tokens):
    """widgets/translucentbackground: a widget on the desktop that asked
    for a see-through background (a clock, a note)."""
    r = tokens["radius"]["overlay"]
    return {"widgets/translucentbackground.svg":
            surface("translucent", r, 0.55, tokens, tooltip_shadow(tokens), (8, 8, 8, 8),
                    mask=False)}


def panels(tokens):
    """The taskbar: square, a 1 px line along its top, acrylic. The
    'thick' margins keep the icons off the edge; the shadow only shows
    when the taskbar is made to float."""
    _, taskbar = alphas(tokens)
    out = {}
    for path, variant, opacity in (("translucent/widgets/panel-background.svg", "translucent", taskbar),
                                   ("widgets/panel-background.svg", "plain", 1),
                                   ("solid/widgets/panel-background.svg", "solid", 1),
                                   ("opaque/widgets/panel-background.svg", "opaque", 1)):
        svg = Svg()
        stack = Stack()
        # the line goes on every side: Plasma turns off the sides that
        # touch the screen edge, so a bottom taskbar shows the top one
        frame(svg, "", 0, stack.next(2 + 16), 0, ("ColorScheme-Background", opacity),
              line=OUTLINE, corner=1)
        hy = stack.next(12)
        margins(svg, "", 0, hy, 1, 0, 0, 0)
        if variant != "opaque":
            margins(svg, "", 40, hy, 0, 0, 0, 0, kind="inset")
        y = stack.next(16)
        svg.add("thick-center", ['<rect x="0" y="%s" width="16" height="16" %s/>'
                                 % (num(y), paint("ColorScheme-Background", opacity))],
                (0, y, 16, 16))
        margins(svg, "thick-", 0, stack.next(12), 2, 2, 2, 2)
        if variant != "opaque":
            extents, strength = tooltip_shadow(tokens)
            _, h = shadow(svg, 0, stack.y, extents, strength, 0, 1)
            stack.next(h)
        out[path] = svg
    return out


def frames(tokens):
    """widgets/frame: plain (an outline), sunken (a well, like a list in
    a popup) and raised (a card)."""
    r = tokens["radius"]["control"]
    svg = Svg()
    stack = Stack()
    kinds = (
        ("plain-", ("ColorScheme-Background", 0), ("ColorScheme-Text", 0.12), (4, 4, 4, 4)),
        ("sunken-", ("#000000", 0.12), ("ColorScheme-Text", 0.08), (4, 4, 4, 4)),
        ("raised-", ("ColorScheme-Text", 0.05), ("ColorScheme-Text", 0.1), (6, 6, 6, 6)),
    )
    for prefix, fill, line, pad in kinds:
        frame(svg, prefix, 0, stack.next(2 * r + 16), r, fill, line=line, mask=False)
        margins(svg, prefix, 0, stack.next(16), *pad)
    return {"widgets/frame.svg": svg}


def plasmoid_heading(tokens):
    """The header and footer bars of popups. The footer is the quick
    settings bottom row: a slightly darker strip with a line above it,
    its bottom corners rounded with the popup's. Darker in both modes: a
    little black, then the scheme's background over it, so it darkens a
    light popup and a dark one by about the same step."""
    r = tokens["radius"]["overlay"]
    divider = ("ColorScheme-Text", 0.08)
    svg = Svg()
    stack = Stack()
    # header: no fill, a divider below
    frame(svg, "header-", 0, stack.next(2 * r + 16), r, ("ColorScheme-Background", 0),
          line=divider, line_sides=("bottom",), mask=False)
    # footer: a darker strip, a divider above, rounded at the bottom only
    footer = [("#000000", 0.1), ("ColorScheme-Background", 0.25)]
    y = stack.next(2 * r + 16)
    frame(svg, "footer-", 0, y, r, footer, line=divider, line_sides=("top",), mask=False)
    # the footer's top corners are square: redraw them as plain tiles
    for name in ("footer-topleft", "footer-topright"):
        i = svg.names.index(name)
        x = 0 if name.endswith("left") else r + 16
        fill = "".join('<rect x="%s" y="%s" width="%s" height="%s" %s/>'
                       % (num(x), num(y), num(r), num(r), paint(*f)) for f in footer)
        svg.body[i] = ('<g id="%s">%s%s</g>'
                       % (name, fill, edge_line("top", x, y, r, r, paint(*divider))))
    # what the header and footer keep around their content
    margins(svg, "", 0, stack.next(16), 8, 8, 8, 8)
    return {"widgets/plasmoidheading.svg": svg}


def render_all(tokens=None):
    tokens = tokens or load_tokens()
    out = {}
    for part in (dialogs, tooltips, widget_backgrounds, translucent_background, panels,
                 frames, plasmoid_heading):
        for path, svg in part(tokens).items():
            out[path] = svg.text()
    return out


def stale(tokens=None):
    old = []
    for path, text in render_all(tokens).items():
        full = os.path.join(OUT, path)
        try:
            with open(full, encoding="utf-8") as f:
                if f.read() == text:
                    continue
        except FileNotFoundError:
            pass
        old.append(path)
    return sorted(old)


def main(argv):
    if "--check" in argv[1:]:
        old = stale()
        for path in old:
            print("not current: desktoptheme/raye/" + path)
        return 1 if old else 0
    for path, text in sorted(render_all().items()):
        full = os.path.join(OUT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as f:
            f.write(text)
        print("desktoptheme/raye/" + path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
